defmodule Brando.Sitemap do
  @moduledoc """
  Sitemaps

  ## Usage

  Start by creating a `MyAppWeb.Sitemap` module and import Brando Sitemap:

      defmodule MyAppWeb.Sitemap do
        import Brando.Sitemap

        sitemap "pages" do
          Brando.Pages.list_pages(
            %{
              filter: Brando.Pages.Page.__url_filter__(),
              status: :published,
              select: {:struct, [:id, :uri, :language, :content_modified_at, :edited_at, :updated_at, :has_url]}
            },
            :stream
          )
          |> Stream.map(fn page ->
            url(%{
              priority: 0.7,
              changefreq: :weekly,
              loc: Brando.Blueprint.URL.resolve(page, :with_host),
              lastmod: Brando.Blueprint.Value.modified_at(page)
            })
          end)
        end
      end

  `Brando.Blueprint.URL.resolve/2` builds each `loc` on the site's own host
  (`Brando.Utils.hostname/0`). Sitemaps are regenerated by an Oban worker at 2am every night.
  To generate an initial sitemap, call `Brando.Sitemap.generate_sitemap/0`
  """

  use Brando.Tracing.Decorator

  require Logger

  alias Brando.Authorization.Boundary
  alias Brando.Tenant
  alias Brando.Tracing
  alias Brando.Utils

  @doc """
  Convenience macro for creating a sitemap function
  """
  defmacro sitemap(key, do: block) do
    quote do
      def unquote(:"__sitemap_for_#{key}__")() do
        unquote(block)
      end
    end
  end

  @doc """
  Convert map to Sitemapper.URL

  `loc` is percent-encoded: a sitemap URL must be, and a slug saved with a
  space in it (`"/news/Some post"`) otherwise makes the whole file invalid.
  An escape already in it (`%20`) is left as it is.
  """
  def url(map), do: Sitemapper.URL |> struct!(map) |> encode_loc() |> check_lastmod()

  defp encode_loc(%Sitemapper.URL{loc: loc} = url) when is_binary(loc) do
    %{url | loc: URI.encode(loc, &(URI.char_unescaped?(&1) or &1 == ?%))}
  end

  defp encode_loc(url), do: url

  @doc """
  Validate that the lastmod has a timezone, or else Google might
  refuse to read it.
  """
  def check_lastmod(%Sitemapper.URL{lastmod: nil} = url), do: url

  def check_lastmod(%Sitemapper.URL{lastmod: %NaiveDateTime{} = lastmod} = url) do
    updated_lastmod =
      lastmod
      |> DateTime.from_naive!("Etc/UTC")
      |> DateTime.shift_zone!(Brando.timezone())

    Map.put(url, :lastmod, updated_lastmod)
  end

  def check_lastmod(%Sitemapper.URL{lastmod: %DateTime{}} = url), do: url

  @doc """
  Drops URLs without a `loc` from one sitemap's entries, logging how many.

  An entry without a URL on this site (`absolute_url ..., only: ...`) has a
  `nil` URL; listed anyway, it would stop the whole generation. Filter such
  entries in the query instead — `filter: Schema.__url_filter__()` — so they
  are never loaded.
  """
  @spec reject_without_loc(Enumerable.t(), atom() | String.t()) :: Enumerable.t()
  def reject_without_loc(urls, sitemap) do
    Stream.transform(
      urls,
      fn -> 0 end,
      fn
        %{loc: loc}, skipped when loc in [nil, ""] -> {[], skipped + 1}
        url, skipped -> {[url], skipped}
      end,
      fn skipped ->
        if skipped > 0 do
          Logger.warning("Sitemap #{sitemap}: skipped #{skipped} entries without a URL. Filter them in its query.")
        end

        {[], skipped}
      end,
      fn _skipped -> :ok end
    )
  end

  @doc """
  Keeps the entries in one of the site's languages (`Brando.Languages`): in
  multi-site mode the languages of the site the sitemap is generated for,
  else the installation's. An entry without a `:language` is kept.

      Pages.list_pages(%{status: :published}, :stream)
      |> in_site_languages()
      |> Stream.map(&url(%{loc: Brando.HTML.absolute_url(&1, :with_host)}))
  """
  @spec in_site_languages(Enumerable.t()) :: Enumerable.t()
  def in_site_languages(entries) do
    codes = Brando.Languages.codes()

    Stream.filter(entries, fn entry ->
      case Map.get(entry, :language) do
        nil -> true
        language -> to_string(language) in codes
      end
    end)
  end

  @doc """
  Check if sitemap exists
  """
  def exists?(module \\ Brando.web_module(Sitemap)) do
    # `function_exported?/3` is false for a module that isn't loaded yet,
    # which is every module in a mix task: load it first.
    Code.ensure_loaded?(module)
  end

  @doc """
  Generate sitemaps

  Gathers all sitemap functions, generates and persists to disk.

  A sitemap describes the public site, so with tenancy it is generated from
  the site's live environment (`source_environment/0`), whichever of its
  environments the process works in, and the index links name the site's
  public base URL (`Brando.Utils.public_hostname/0`). The site's
  environments share the files. It reads as the system, whoever calls it: the
  sitemap lists what visitors see, not what the caller's admin scope may read.

  ## Options

  Options are passed on to Sitemapper.

    * `:gzip` (default: `true`) - Sets whether the files are gzipped

  """
  # Not decorated directly: its implicit `rescue` would become a second span.
  @decorate span("brando.sitemap.generate")
  def generate_sitemap(opts \\ []) do
    # Unscoped: an admin's scope keeps naming the environment it was taken in
    Boundary.with_scope(nil, fn -> in_source_environment(fn -> do_generate_sitemap(opts) end) end)
  end

  defp in_source_environment(fun) do
    case source_environment() do
      nil -> fun.()
      live -> Tenant.with_prefix(Tenant.prefix(Tenant.current_site_key(), live.key), fun)
    end
  end

  @doc """
  The environment `generate_sitemap/1` reads: the live environment of the
  site the process's tenant prefix names, or `nil` outside a site (and in
  `:none`), where it reads the current schema.
  """
  @spec source_environment() :: Brando.Environments.Environment.t() | nil
  def source_environment do
    case Tenant.current_site_key() do
      nil -> nil
      site_key -> Tenant.Cache.get_live_env(site_key)
    end
  end

  defp do_generate_sitemap(opts) do
    sitemap_path = Path.join([Brando.Tenant.Storage.current_media_root(), "sitemaps"])
    persist(Brando.web_module(Sitemap), sitemap_path, opts)
  rescue
    UndefinedFunctionError ->
      :ok
  end

  @doc """
  Writes the sitemap of the environment the process works in to `path`, for
  a static build (`Brando.SSG.build/3`): the files `generate_sitemap/1`
  writes, from `:module` (by default the application's `Sitemap`), with the
  index naming them under the site's public base URL
  (`Brando.Utils.public_hostname/0`) and entries on the site's own host moved
  to that base URL too. Unlike `generate_sitemap/1` it reads the environment
  the process works in, not the live one, and it reads as the system.

  `{:ok, file_names}`, `{:ok, []}` without a sitemap module (`module: nil` for none) or entries, or
  `{:error, message}` when generating raised. Other options go to Sitemapper.
  """
  @spec write_static(String.t(), keyword()) :: {:ok, [String.t()]} | {:error, String.t()}
  def write_static(path, opts \\ []) do
    {module, opts} = Keyword.pop_lazy(opts, :module, &Brando.sitemap/0)

    if is_atom(module) and not is_nil(module) and exists?(module) do
      Boundary.with_scope(nil, fn ->
        File.mkdir_p!(path)
        {:ok, files} = persist(module, path, opts)
        {:ok, Enum.map(files, fn {file_name, _body} -> file_name end)}
      end)
    else
      {:ok, []}
    end
  rescue
    exception -> {:error, Exception.message(exception)}
  end

  defp persist(sitemap_module, sitemap_path, opts) do
    sitemap_functions = sitemap_module.__info__(:functions)
    site_base = Utils.hostname()
    public_base = Utils.public_hostname()

    entries =
      Stream.flat_map(sitemap_functions, fn {fun, _arity} ->
        sitemap_module
        |> apply(fun, [])
        |> reject_without_loc(fun)
        |> Stream.map(&on_public_base(&1, site_base, public_base))
      end)

    File.mkdir_p!(sitemap_path)

    default_opts = [
      sitemap_url: Utils.public_hostname("sitemaps"),
      store: Sitemapper.FileStore,
      store_config: [
        path: sitemap_path
      ]
    ]

    opts = Keyword.merge(default_opts, opts)

    Brando.Repo.transaction(fn ->
      entries
      |> Sitemapper.generate(opts)
      |> Sitemapper.persist(opts)
      |> Enum.to_list()
      |> tap(&Tracing.set_attributes(%{"brando.file_count": length(&1)}))
    end)
  end

  # An entry on the host of the environment the process works in names the
  # public base URL instead, as a stored sitemap must. The same URL when the
  # environment is the live one.
  defp on_public_base(url, base, base), do: url

  defp on_public_base(%Sitemapper.URL{loc: loc} = url, site_base, public_base) when is_binary(loc) do
    %{url | loc: rebase(loc, site_base, public_base)}
  end

  defp on_public_base(url, _site_base, _public_base), do: url

  defp rebase(loc, site_base, public_base) do
    cond do
      loc == site_base -> public_base
      String.starts_with?(loc, site_base <> "/") -> public_base <> String.replace_prefix(loc, site_base, "")
      true -> loc
    end
  end
end
