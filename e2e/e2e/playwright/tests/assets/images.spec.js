import { test, expect } from '../../test-support/setupAuth'
import { syncLV } from '../../utils'

test('browses folders, uploads and searches images without exposing folder filters', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  let fixture
  try {
    await page.goto('/admin/assets/images')
    await syncLV(page)
    await page.getByRole('button', { name: 'New folder', exact: true }).click()
    await page.getByPlaceholder('Folder name', { exact: true }).fill('design-review')
    await page.getByRole('button', { name: 'Create folder', exact: true }).click()
    const path = page.getByRole('navigation', { name: 'Folder path' })
    await expect(path).toContainText('design-review')
    await expect(page).toHaveURL(/filter(%3A|:)folder_id=/)
    await expect(page.locator('.active-filters')).toHaveCount(0)
    await expect(page.getByRole('heading', { name: 'No images in this view' })).toBeVisible()
    await syncLV(page)
    await expect(page.locator('body > canvas')).toBeHidden()
    await page.screenshot({ path: testInfo.outputPath('images-empty-desktop.png'), fullPage: true })

    await page.getByLabel('Upload images', { exact: true }).setInputFiles('./fixtures/image.jpg')
    const rows = page.locator('.content-list .list-row')
    await expect(rows).toHaveCount(1)
    await expect(rows.first().locator('.library-thumbnail img')).toBeVisible({ timeout: 30000 })
    await expect(rows.first()).toContainText('No alt text')
    await expect(rows.first().getByRole('group', { name: 'Formats' })).toContainText('JPG')
    await expect(rows.first().locator('.library-size-count')).toContainText(/\d+ sizes?/)
    await expect(page.getByText('1 image', { exact: true })).toBeVisible()
    const filename = await rows.first().getByRole('link').innerText()

    const search = page.getByRole('textbox', { name: 'Filter by Path', exact: true })
    await search.fill('does-not-exist')
    await expect(rows).toHaveCount(0)
    await expect(page.locator('.active-filters')).not.toContainText('folder_id')
    await search.fill('')
    await expect(rows).toHaveCount(1)
    await page.getByRole('button', { name: 'Root', exact: true }).click()
    await expect(path).not.toContainText('design-review')
    await expect(rows.filter({ hasText: filename })).toHaveCount(0)
    await page.getByRole('complementary').getByRole('button', { name: 'design-review', exact: true }).click()
    await expect(rows).toHaveCount(1)
    await expect(rows.first()).toContainText(filename)
    const imageId = (await rows.first().getAttribute('id')).replace('list-row-', '')
    const fixtureResponse = await page.request.post(`/e2e/image-creator/${imageId}`)
    expect(fixtureResponse.ok()).toBe(true)
    fixture = await fixtureResponse.json()
    await page.reload()
    await syncLV(page)
    await expect(rows.first()).toContainText(filename)
    const avatar = rows.first().locator('.item-meta .avatar img')
    await expect(avatar).toBeVisible()
    await expect.poll(() => avatar.evaluate(img => img.naturalWidth)).toBeGreaterThan(0)
    await expect(rows.first()).toContainText('Image contributor')
    await expect(page.locator('body > canvas')).toBeHidden()
    await page.screenshot({ path: testInfo.outputPath('images-desktop.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(avatar).toBeVisible()
    expect((await avatar.boundingBox()).width).toBe(30)
    await page.screenshot({ path: testInfo.outputPath('images-mobile.png'), fullPage: true })
  } finally {
    if (fixture) await page.request.post('/e2e/user-directory/cleanup', { data: fixture })
  }
})
