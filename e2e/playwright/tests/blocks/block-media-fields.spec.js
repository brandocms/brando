test('a queued replacement cannot reattach an image after Remove', async ({ page }, testInfo) => {
  await createPage(page, 'Ignore removed upload', 'Single Image with Caption')
  await drop(page, picture(page), [['image.jpg', 'image/jpeg']])
  await confirmUploadFolder(page)
  await expect(picture(page).locator('img')).toBeVisible({ timeout: 20000 })
  // Hold the real manager queue before transfer so the intervening edit is deterministic.
  await page.evaluate(() => { window.BrandoUploads._hook._maxTransfers = 0 })
  await drop(page, picture(page), [['image2.jpg', 'image/jpeg']])
  const queued = page.locator('.upload-item.status-queued').filter({ hasText: 'image2.jpg' })
  await expect(queued).toBeVisible()
  await expect(picture(page).getByRole('status')).toContainText('Waiting to upload')
  await page.screenshot({ path: testInfo.outputPath('field-and-sticky-queue.png') })
  await picture(page).getByRole('button', { name: 'Remove', exact: true }).click()
  await page.evaluate(() => { window.BrandoUploads._hook._maxTransfers = 3; window.BrandoUploads._hook.pumpTransfers() })
  await expect(page.locator('.upload-item.status-done').filter({ hasText: 'image2.jpg' })).toBeVisible({ timeout: 20000 })
  await expect(picture(page).getByRole('button', { name: 'Upload', exact: true })).toBeVisible()
  await expect(picture(page).locator('img')).toHaveCount(0)
})

