import { test, expect } from '../../test-support/setupAuth'
import { syncLV } from '../../utils'

test('deleting a page variable preserves the remaining label through save and reload', async ({ page }) => {
  await page.request.post('/e2e/setup_fixtures/norwegian-admin-user')
  await page.goto('/admin/pages/create')
  await syncLV(page)
  await page.getByLabel('Tittel', { exact: true }).fill('Variable labels')
  await page.getByLabel('URI', { exact: true }).fill('variable-labels')
  await page.getByRole('button', { name: 'Avansert', exact: true }).click()
  const vars = page.locator('.subform--vars')
  const rows = vars.locator('.vars-row')
  await vars.getByRole('button', { name: 'Ny rad', exact: true }).click()
  await vars.getByRole('button', { name: 'Ny rad', exact: true }).click()
  await expect(rows).toHaveCount(2)
  await expect(rows.locator('.variable-key > span')).toHaveText(['Label', 'Label'])
  await rows.first().locator('.subform-delete').click()
  await expect(rows).toHaveCount(1)
  await expect(rows.locator('.variable-key > span')).toHaveText('Label')
  await rows.locator('.variable-header').click()
  await expect(rows.locator('input[name$="[label][en]"]')).toHaveValue('Label')
  await page.getByTestId('submit').click()
  await expect(page).toHaveURL('/admin/pages')
  await page.getByRole('link', { name: 'Variable labels', exact: true }).click()
  await syncLV(page)
  await page.getByRole('button', { name: 'Avansert', exact: true }).click()
  await expect(rows).toHaveCount(1)
  await expect(rows.locator('.variable-key > span')).toHaveText('Label')
})
