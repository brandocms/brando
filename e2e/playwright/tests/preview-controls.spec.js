import { test, expect } from '../test-support/setupAuth'
import { syncLV, waitForPreviewReady } from '../utils'

test('preview resize keeps capture across the iframe and bounds, and devices retain selection', async ({ page }, testInfo) => {
  await page.request.post('/e2e/setup_fixtures/norwegian-admin-user')
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/admin/pages/update/1')
  await syncLV(page)
  await page.locator('.live-preview-toggle').click()
  await page.locator('.preview-choice').first().click()
  await waitForPreviewReady(page)
  const preview = page.locator('.live-preview')
  const divider = page.getByRole('separator', { name: 'Endre størrelse på forhåndsvisning' })
  const width = () => preview.evaluate(el => Math.round(el.getBoundingClientRect().width))
  await expect.poll(width).toBe(600)
  const handle = await divider.boundingBox()
  expect(handle.height).toBeGreaterThan(900)
  await page.mouse.move(handle.x + 5, handle.y + 220)
  await page.mouse.down()
  // Go well past the smallest width, then back, without releasing. The old
  // resizer terminated the drag at the boundary (and when entering iframe).
  await page.mouse.move(1580, 450, { steps: 5 })
  await expect.poll(width).toBe(320)
  await page.mouse.move(handle.x - 60, 450, { steps: 5 })
  await expect.poll(width).toBe(665)
  await page.mouse.move(100, 450, { steps: 5 })
  await expect.poll(width).toBe(795)
  await page.mouse.move(handle.x + 5, 450, { steps: 5 })
  await expect.poll(width).toBe(600)
  await page.mouse.up()
  await expect(preview).not.toHaveClass(/is-resizing/)

  await divider.focus()
  await page.keyboard.press('ArrowRight')
  await expect.poll(width).toBe(576)
  await page.keyboard.press('ArrowLeft')
  await expect.poll(width).toBe(600)
  const mobile = page.getByRole('button', { name: '375px', exact: true })
  await mobile.click()
  await expect(mobile).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#live-preview-frame')).toHaveAttribute('data-live-preview-device', 'mobile')
  await expect.poll(width).toBe(375)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(mobile).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(width).toBe(375)
  await page.getByRole('button', { name: '768px', exact: true }).hover()
  await page.screenshot({ path: testInfo.outputPath('preview-toolbar.png') })
  await page.getByRole('button', { name: 'Oppdater', exact: true }).click()
  await waitForPreviewReady(page)
  await expect(mobile).toHaveAttribute('aria-pressed', 'true')
  // Closing from the keyboard returns focus to the trigger, not to the page.
  await page.getByRole('button', { name: 'Lukk forhåndsvisningen', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(preview).toHaveCount(0)
  await expect(page.locator('.preview-chooser-trigger')).not.toHaveClass(/active/)
  await expect(page.locator('.preview-chooser-trigger')).toBeFocused()
})
